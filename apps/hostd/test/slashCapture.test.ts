test("replays image-72 transcript: drops command-caveat, turns failed /model and /effort into command_error, keeps /cost stdout", () => {
  const S = "codebuddy:01a2080e";
  const rawEvents = [
    {
      id: "e14",
      session: S,
      ts: 1000,
      kind: "user_message" as const,
      text: '<system-reminder data-role="command-caveat">Caveat: The messages below were generated by the user while running local commands.</system-reminder>',
    },
    {
      id: "e15",
      session: S,
      ts: 1001,
      kind: "user_message" as const,
      text: "<command-name>/help</command-name>",
    },
    {
      id: "e16",
      session: S,
      ts: 1500,
      kind: "user_message" as const,
      text: "<local-command-stdout></local-command-stdout>",
    },
    {
      id: "e27",
      session: S,
      ts: 2000,
      kind: "user_message" as const,
      text: '<system-reminder data-role="command-caveat">Caveat: The messages below were generated by the user while running local commands.</system-reminder>',
    },
    {
      id: "e28",
      session: S,
      ts: 2001,
      kind: "user_message" as const,
      text: "<command-name>/model</command-name>\n<command-args>gpt-6.2-astra-fast</command-args>",
    },
    {
      id: "e29",
      session: S,
      ts: 2004,
      kind: "user_message" as const,
      text: '<local-command-stdout>Error: Model "gpt-6.2-astra-fast" is not available.\n\nAvailable models:\n  - DeepSeek-V4.1-Flash</local-command-stdout>',
    },
    {
      id: "e30",
      session: S,
      ts: 3000,
      kind: "user_message" as const,
      text: '<system-reminder data-role="command-caveat">Caveat: ...</system-reminder>',
    },
    {
      id: "e32",
      session: S,
      ts: 3001,
      kind: "user_message" as const,
      text: "<command-name>/effort</command-name>\n<command-args>xhigh</command-args>",
    },
    {
      id: "e33",
      session: S,
      ts: 3002,
      kind: "user_message" as const,
      text: "<local-command-stdout>`xhigh` is not supported by the current model. Supported: `low` / `high` / `max`.</local-command-stdout>",
    },
    {
      id: "e40",
      session: S,
      ts: 4001,
      kind: "user_message" as const,
      text: "<command-name>/cost</command-name>",
    },
    {
      id: "e41",
      session: S,
      ts: 4002,
      kind: "user_message" as const,
      text: "<local-command-stdout>Total cost: $0.14\nTokens: 12k</local-command-stdout>",
    },
  ];

  const cleaned = rawEvents.map((e) => cleanEvent(e as any)).filter((e): e is NonNullable<typeof e> => e !== null);
  const finalEvents = coalesceLocalCommandEvents(cleaned);

  assert.equal(
    finalEvents.some((e) => e.kind === "system" && e.summary === "系统提醒"),
    false,
    "command-caveat must not emit 系统提醒",
  );
  assert.equal(
    finalEvents.some((e) => e.kind === "system" && e.subtype === "model_switch"),
    false,
    "failed /model and /effort must never emit false model_switch",
  );

  const errEvents = finalEvents.filter(
    (e): e is Extract<ConvEvent, { kind: "system" }> => e.kind === "system" && e.subtype === "command_error",
  );
  assert.equal(errEvents.length, 2);
  assert.equal(errEvents[0]?.summary, "/model gpt-6.2-astra-fast");
  assert.match(errEvents[0]?.text ?? "", /not available/);
  assert.equal(errEvents[1]?.summary, "/effort xhigh");
  assert.match(errEvents[1]?.text ?? "", /not supported/);

  const costOut = finalEvents.find(
    (e): e is Extract<ConvEvent, { kind: "system" }> => e.kind === "system" && e.subtype === "command_output",
  );
  assert.ok(costOut);
  assert.equal(costOut.summary, "/cost");
  assert.match(costOut.text, /Total cost: \$0\.14/);
});

test("sendAndCaptureSlashCommand captures TUI viewer panels and auto-dismisses with Esc while keeping interactive pickers open", async () => {
  assert.equal(classifySlashCommand("codex", "/status"), "viewer");
  assert.equal(classifySlashCommand("claude-code", "/config"), "interactive");
  assert.equal(classifySlashCommand("claude-code", "explain this file"), "normal");

  const keysSent: string[][] = [];
  let screen = "❯ ";
  const viewerRes = await sendAndCaptureSlashCommand(
    {
      snapshotText: async () => screen,
      send: async () => {
        screen = [
          "╭─── Codex Status ───────────╮",
          "│ Model: gpt-5-codex         │",
          "│ Context left: 82%          │",
          "╰─ Esc to close ─────────────╯",
        ].join("\n");
      },
      keys: async (_id, k) => {
        keysSent.push(k);
        screen = "❯ ";
      },
    },
    "t1",
    { harness: "codex", isShell: false },
    "/status",
  );
  assert.equal(viewerRes?.command, "/status");
  assert.match(viewerRes?.output ?? "", /Model: gpt-5-codex/);
  assert.equal(viewerRes?.panelState, "closed");
  assert.deepEqual(keysSent, [["esc"]]);

  const keysPicker: string[][] = [];
  let pickerScreen = "❯ ";
  const pickerRes = await sendAndCaptureSlashCommand(
    {
      snapshotText: async () => pickerScreen,
      send: async () => {
        pickerScreen = [
          "Settings",
          "1. Theme: Light",
          "Esc to cancel",
        ].join("\n");
      },
      keys: async (_id, k) => {
        keysPicker.push(k);
        pickerScreen = "❯ ";
      },
    },
    "t1",
    { harness: "claude-code", isShell: false },
    "/config",
  );
  assert.equal(pickerRes?.panelState, "closed");
  assert.deepEqual(keysPicker, [["esc"]]);

  // Prefers fast dismissSubscreens over raw keys when available.
  let dismissedFast = false;
  let fastScreen = "❯ ";
  const fastRes = await sendAndCaptureSlashCommand(
    {
      snapshotText: async () => fastScreen,
      send: async () => {
        fastScreen = "╭─ Usage ─╮\n│ Tokens: 100 │\n╰─ Esc to close ─╯";
      },
      keys: async () => {
        throw new Error("should use dismissSubscreens first");
      },
      dismissSubscreens: async () => {
        dismissedFast = true;
        fastScreen = "❯ ";
        return "viewer";
      },
    },
    "t1",
    { harness: "codex", isShell: false },
    "/usage",
  );
  assert.equal(dismissedFast, true);
  assert.equal(fastRes?.panelState, "closed");
});

test("cleanEvent suppresses leaked harness tags and normalizes checkpoint/compact_boundary events", () => {
  assert.equal(
    cleanEvent({ id: "l1", session: "s", ts: 1, kind: "system", text: "<SYSTEM_MESSAGE>internal</SYSTEM_MESSAGE>" } as any),
    null,
  );
  assert.equal(
    cleanEvent({ id: "l2", session: "s", ts: 2, kind: "system", subtype: "developer", text: "<session_context>cwd=/repo</session_context>" } as any),
    null,
  );
  assert.equal(
    cleanEvent({ id: "l3", session: "s", ts: 3, kind: "user_message", text: "[Image: original 100x100]", synthetic: true } as any),
    null,
  );
  const cp = cleanEvent({ id: "l4", session: "s", ts: 4, kind: "system", subtype: "compact_boundary", text: "compacted" } as any) as any;
  assert.equal(cp?.subtype, "compact");
  assert.equal(cp?.summary, "上下文已压缩");
});
