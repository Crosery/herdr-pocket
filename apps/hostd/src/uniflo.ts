/** Subset of Uniflo schema v1 `Session` (crates/uniflo-schema/src/lib.rs). */
export interface UnifloSession {
  key: string;
  harness: string;
  title?: string;
  cwd?: string;
  model?: string;
  source?: string;
  preview?: string;
  updated_at: number;
  status: "idle" | "work";
  pid?: number;
  parent?: string;
  parent_call?: string;
  started_at?: number;
  status_since?: number;
  usage?: { cost_usd?: number; last_context_tokens?: number; context_limit?: number; steps?: number };
}

/** Clock slack between a terminal's creation (hc) and a session's start (Uniflo), same machine. */
const BORN_SLACK_MS = 2000;

/** The parts of a session that change what agents show: a new one, its status, process or title. */
const sessionSig = (s: UnifloSession): string => `${s.status}|${s.pid ?? ""}|${s.title ?? ""}|${s.parent ?? ""}`;

const plain = (s: string | undefined, max: number): string | undefined =>
  s ? s.replace(/<\/?[\w-]+[^>]*>/g, " ").replace(/\s+/g, " ").trim().slice(0, max) || undefined : undefined;

function toInfo(s: UnifloSession): SessionInfo {
  return {
    key: s.key,
    harness: s.harness,
    title: cleanTitle(s.title),
    cwd: s.cwd,
    model: s.model,
    preview: plain(s.preview, 200),
    status: s.status === "work" ? "working" : "idle",
    startedAt: s.started_at,
    updatedAt: s.updated_at,
    costUsd: s.usage?.cost_usd,
    steps: s.usage?.steps,
    parent: s.parent,
  };
}

function toUsage(r: Record<string, unknown>): UsageRow {
  const n = (k: string) => (typeof r[k] === "number" ? (r[k] as number) : 0);
  return {
    key: String(r.key ?? ""),
    label: String(r.label ?? r.key ?? ""),
    sessions: n("sessions"),
    steps: n("steps"),
    prompts: n("prompts"),
    input: n("input"),
    output: n("output"),
    cacheRead: n("cache_read"),
    cacheWrite: n("cache_write"),
    costUsd: n("cost_usd"),
  };
}

/** Harness-injected blocks (skill routers, reminders, hooks) that are not part of the conversation. */
const INJECTED_TAG =
  /<(skill-recommendation|system-reminder|system_message|ephemeral_message|session_context|system|user-prompt-submit-hook|command-(?:name|message|args)|local-command-(?:stdout|stderr|caveat)|environment_context|context|instructions)\b[^>]*>[\s\S]*?<\/\1>/gi;

const ANSI_CLEAN_RE = /\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)|\x1b[@-_]/g;

function isEmptyLocalCommandStdout(raw: string): boolean {
  const m = /^\s*<local-command-(?:stdout|stderr)>([\s\S]*?)<\/local-command-(?:stdout|stderr)>\s*$/i.exec(raw);
  if (!m) return false;
  return !m[1]!.replace(ANSI_CLEAN_RE, "").trim();
}

function isLeakedHarnessNoise(raw: string, subtype?: string): boolean {
  const sub = subtype?.trim().toLowerCase();
  if (sub === "system_message" || sub === "developer") return true;
  const trimmed = raw.trim();
  if (!trimmed) return true;
  if (/^<(?:SYSTEM_MESSAGE|ephemeral_message|session_context|INSTRUCTIONS)\b[\s\S]*<\/(?:SYSTEM_MESSAGE|ephemeral_message|session_context|INSTRUCTIONS)>\s*$/i.test(trimmed)) {
    return true;
  }
  if (/^\[Image:\s*original\b[^\]]*\]$/i.test(trimmed)) return true;
  if (/^Base directory for this skill:\s+\S+$/i.test(trimmed)) return true;
  return false;
}

function isBoilerplateCommandCaveat(raw: string): boolean {
  const stripped = raw
    .replace(/<local-command-caveat\b[^>]*>[\s\S]*?<\/local-command-caveat>/gi, "")
    .replace(/<system-reminder\b[^>]*data-role=["']command-caveat["'][^>]*>[\s\S]*?<\/system-reminder>/gi, "")
    .replace(/<environment_context\b[^>]*>[\s\S]*?<\/environment_context>/gi, "")
    .trim();
  if (!stripped) return true;
  if (/^\s*Caveat:\s*The messages below were generated by the user while running local commands\b/i.test(stripped)) {
    return true;
  }
  return false;
}

/** One readable line for an injected block, e.g. `推荐技能 docs` or `已切换模型为 ...`. */
export function summarizeInjected(text: string, subtype?: string): string {
  const sw = parseModelSwitchText(text, subtype);
  if (sw && (sw.model || sw.thinking)) return formatModelSwitchSummary(sw);

  const cmdTag = parseSlashCommandTag(text);
  if (cmdTag) return `命令 ${cmdTag.full}`.slice(0, 60);

  const localOut = parseLocalCommandOutputTag(text);
  if (localOut) {
    const body = localOut.body.replace(/\s+/g, " ").trim();
    if (localOut.isError) return body ? `命令失败 · ${body.slice(0, 44)}` : "命令失败";
    return body ? `命令输出 · ${body.slice(0, 44)}` : "命令已执行";
  }

  const skill = /<skill-recommendation\b[^>]*\bname="([^"]+)"/.exec(text);
  if (skill) return `推荐技能 ${skill[1]}`;
  if (/<system-reminder\b/.test(text)) return "系统提醒";
  const tag = /^\s*<([\w-]+)/.exec(text);
  if (tag) return tag[1]!;
  const sub = subtype?.split(".").pop();
  const line = text.trim().split("\n")[0] ?? "";
  return sub ? `${sub}${line ? ` · ${line.slice(0, 40)}` : ""}` : line.slice(0, 60) || "系统消息";
}

function finalizeSystemNote(
  e: ConvEvent & Record<string, unknown>,
  text: string,
  subtype?: string,
): ConvEvent | null {
  if (!text || isEmptyLocalCommandStdout(text) || isBoilerplateCommandCaveat(text)) return null;
  const subLower = subtype?.trim().toLowerCase();
  if (subLower === "checkpoint" || subLower === "compact_boundary" || subLower === "compact") {
    return {
      ...e,
      kind: "system",
      text,
      subtype: "compact",
      summary: typeof e.summary === "string" && e.summary.trim() ? e.summary.trim() : "上下文已压缩",
    } as ConvEvent;
  }
  const localOut = parseLocalCommandOutputTag(text);
  if (localOut) {
    if (!localOut.body || isDismissedCommandOutput(localOut.body)) {
      return null;
    }
    const swOut = localOut.isError ? null : parseModelSwitchText(text, subtype);
    if (swOut && (swOut.model || swOut.thinking)) {
      return {
        ...e,
        kind: "system",
        text: localOut.body,
        subtype: "model_switch",
        summary: formatModelSwitchSummary(swOut),
      } as ConvEvent;
    }
    if (swOut?.ackOnly) return null;
    return {
      ...e,
      kind: "system",
      text: localOut.body,
      subtype: localOut.isError ? "command_error" : "command_output",
      summary: localOut.isError ? "命令失败" : "命令输出",
    } as ConvEvent;
  }

  const sw = parseModelSwitchText(text, subtype);
  if (sw) {
    if (sw.model || sw.thinking) {
      return {
        ...e,
        kind: "system",
        text,
        subtype: "model_switch",
        summary: formatModelSwitchSummary(sw),
      } as ConvEvent;
    }
    if (sw.ackOnly) return null;
  }
  if (isLeakedHarnessNoise(text, subtype)) return null;
  const cmdTag = parseSlashCommandTag(text);
  const resolvedSubtype = subtype ?? (cmdTag ? "command" : /<system-reminder\b/i.test(text) ? "reminder" : undefined);
  return {
    ...e,
    kind: "system",
    text,
    ...(resolvedSubtype ? { subtype: resolvedSubtype } : {}),
    summary: summarizeInjected(text, resolvedSubtype),
  } as ConvEvent;
}

/**
 * Coalesces `[command echo, local-command-stdout/stderr]` pairs so failed `/model` or `/effort`
 * switches become a single `command_error` row (never a false `model_switch`), `/cost` or `/context`
 * outputs carry their command label, and consecutive identical `system` rows deduplicate cleanly.
 */
export function coalesceLocalCommandEvents(events: ConvEvent[]): ConvEvent[] {
  const out: ConvEvent[] = [];
  for (let i = 0; i < events.length; i += 1) {
    const cur = events[i]!;
    const next = i + 1 < events.length ? events[i + 1] : undefined;
    if (
      cur.kind === "system" &&
      next?.kind === "system" &&
      Math.abs((next.ts ?? 0) - (cur.ts ?? 0)) <= 15_000 &&
      (next.subtype === "command_output" || next.subtype === "command_error")
    ) {
      const tag = parseSlashCommandTag(cur.text);
      const isModelCmd = cur.subtype === "model_switch" || (tag && /^\/(?:model|models|switch|effort|thinking)$/i.test(tag.name));
      if (tag || isModelCmd) {
        const cleanBody = next.text.replace(ANSI_CLEAN_RE, "").trim();
        const label = tag?.full ?? cur.summary?.replace(/^命令\s+/, "") ?? "命令";
        const isErr = next.subtype === "command_error" || isCommandErrorOutput(cleanBody);
        if (isDismissedCommandOutput(cleanBody)) {
          i += 1;
          continue;
        }
        out.push({
          ...next,
          id: cur.id,
          ts: cur.ts,
          pos: cur.pos ?? next.pos,
          kind: "system",
          subtype: isErr ? "command_error" : "command_output",
          summary: label,
          text: cleanBody,
        });
        i += 1;
        continue;
      }
    }
    const prev = out[out.length - 1];
    if (
      cur.kind === "system" &&
      prev?.kind === "system" &&
      prev.subtype === cur.subtype &&
      prev.summary === cur.summary &&
      prev.text === cur.text
    ) {
      continue;
    }
    out.push(cur);
  }
  return out;
}

/**
 * Separates what the person wrote and the agent said from what the harness injected.
 * Injected content is kept (folded) so nothing is lost; usage ticks and empty command noise are dropped.
 */
export function cleanEvent(e: ConvEvent & Record<string, unknown>): ConvEvent | null {
  if (e.kind === "usage") return null;
  if (e.kind === "system") {
    const text = typeof e.text === "string" ? e.text.trim() : "";
    return finalizeSystemNote(e, text, e.subtype);
  }
  if (e.kind === "user_message" && typeof e.text === "string") {
    if (e.synthetic) return finalizeSystemNote(e, e.text.trim(), "自动插入");
    const blocks = e.text.match(INJECTED_TAG);
    if (!blocks) {
      const sw = parseModelSwitchText(e.text);
      if (sw && (sw.model || sw.thinking)) {
        return {
          ...e,
          kind: "system",
          text: e.text.trim(),
          subtype: "model_switch",
          summary: formatModelSwitchSummary(sw),
        } as ConvEvent;
      }
      if (sw?.ackOnly) return null;
      return e;
    }
    const text = e.text.replace(INJECTED_TAG, "").replace(/\n{3,}/g, "\n\n").trim();
    const injected = blocks.join("\n\n");
    if (!text) return finalizeSystemNote(e, injected);
    return { ...e, text, injected };
  }
  return e;
}

/** The longest tool output the phone gets; it shows a preview. */
const TOOL_OUTPUT_MAX = 4000;

/** What the phone gets for one Uniflo event: injected blocks folded, usage ticks dropped, long tool output clipped. */
export function toConvEvent(raw: ConvEvent & Record<string, unknown>): ConvEvent | null {
  const e = cleanEvent(raw);
  if (!e) return null;
  const out = { ...e, pos: e.pos === undefined || e.pos === null ? undefined : String(e.pos) };
  if (e.kind === "tool_result" && typeof e.output === "string" && e.output.length > TOOL_OUTPUT_MAX) {
    return { ...out, output: `${e.output.slice(0, TOOL_OUTPUT_MAX)}\n…`, truncated: true } as ConvEvent;
  }
  return out as ConvEvent;
}

/** `max_text` asked of the events API. */
const PAGE_TEXT_MAX = 6000;

/**
 * True when the events API returns this live-stream event unchanged: no field is long enough for
 * `max_text` to cut. Counted in UTF-8 bytes with room to spare, so it holds however Uniflo counts.
 */
export function sameAsPage(raw: Record<string, unknown>): boolean {
  for (const v of Object.values(raw)) {
    if (v === null || v === undefined || typeof v === "number" || typeof v === "boolean") continue;
    if (Buffer.byteLength(typeof v === "string" ? v : JSON.stringify(v)) > PAGE_TEXT_MAX - 200) return false;
  }
  return true;
}

